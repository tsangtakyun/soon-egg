const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
function load(file) {
  const box = { exports: {} };
  const code = ts.transpileModule(fs.readFileSync(`src/lib/credits/${file}.ts`, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  Function('module', 'exports', 'require', code)(box, box.exports, name => { if (name === './policy') return load('policy'); throw Error(name); });
  return box.exports;
}
const m = load('preview-model');
const input = { workspace:'a', actor:'u', key:'k', hash:'h', action:'egg_this_generate', now:0 };
