assert.equal(wallet.balance,25);
assert.equal(m.previewReserve(wallet,input),wallet);
for (const edit of [{actor:'other'},{hash:'other'},{workspace:'b'}]) assert.throws(() => m.previewReserve(wallet,{...input,...edit}));
wallet = m.previewUnknown(wallet,'k',1000);
